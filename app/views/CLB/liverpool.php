    <p><h5>Sân được chia thành bốn phần: Spion Kop, khán đài chính (Main Stand), khán đài Sir Kenny Dalglish (Sir Kenny Dalglish Stand, trước đó tên là Centenary Stand) và khán đài đường Anfield (Anfield Road), với sức chứa tổng cộng 54.074, biến nó thành sân vận động bóng đá lớn thứ 7 ở Anh. Số lượng cổ động viên tham gia kỷ lục là 61.905 đã được thiết lập trong trận đấu giữa Liverpool và Wolverhampton Wanderers năm 1952. Sân vận động đã giảm sức chứa vào năm 1994 do Báo cáo Taylor.</h5></p>
    <p><h5>Có một số công trình nổi tiếng của sân vận động bao gồm 2 cổng có tên 2 cựu HLV của Liverpool: Cổng Bob Paisley và cổng Bill Shankly. Ngoài ra còn có tượng của Shankly ở bên ngoài sân vận động. Sân cách ga xe lửa Liverpool Lime Street 3 km. Dự định rằng vào năm 2002 họ sẽ thay thế sân vận động bằng một sân mới ở sát Công viên Stanley, nhưng sau khi Fenway Sports Group mua lại Liverpool F.C. vào năm 2010, dự định trên không diễn ra nữa.</h5></p>
    <p><h5>Anfield là một sân vận động đạt chuẩn UEFA, và đã tổ chức nhiều trận đấu quốc tế, bao gồm cả những trận của đội tuyển Anh. Sân cũng được sử dụng ở VCK Euro 1996. Ban đầu sân cũng còn được sử dụng trong nhiều hoạt động, chẳng hạn như những trận boxing và tennis.</h5><p>
    <p><h5>Việc xây dựng mở rộng cho khán đài Main Stand bắt đầu vào ngày 8 tháng 12 năm 2014. Nó mở cửa lại cho công chúng vào ngày 9 tháng 9 năm 2016 khi tăng sức chứa sân vận động lên 54.074, khiến nó trở thành một trong những khán đài lớn nhất toàn cầu trong nền bóng đá châu Âu. Kế hoạch trong tương lai là việc mở rộng khán đài Anfield Road Stand giúp đưa quy mô sân vận động lên khoảng 61.000 chỗ.</h5><p>
